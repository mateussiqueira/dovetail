#!/usr/bin/env bash
set -u
export LC_ALL=C
RAIZ="$(git rev-parse --show-toplevel)" || exit 1
cd "$RAIZ" || exit 1
CONF=scripts/checks/pre_commit.conf
LISTA=scripts/checks/forbidden_words.sha256
export SENSIVEL='(^|/)\.env($|\.)|\.(pem|p12|pfx|jks|keystore|ppk)$|key\.properties$|(^|/)id_(rsa|dsa|ecdsa|ed25519)$'
export PALAVRA='secret|password|token|api.key|credential'
export FONTE='\.(go|rs|dart|kt|kts|java|swift|m|h|gradle|sh|ya?ml|md|json|sql|tmpl)$'
SEGREDO='-----BEGIN[ A-Z0-9_-]*PRIVATE KEY|(AKIA|ASIA|ABIA|ACCA)[0-9A-Z]{16}|gh[pousr]_[A-Za-z0-9]{36}|github_pat_[A-Za-z0-9_]{22,}|xox[abprs]-[A-Za-z0-9-]{10,}|://[0-9a-f]{32}(:[0-9a-f]{32})?@|AIza[0-9A-Za-z_-]{35}|[sr]k_live_[0-9A-Za-z]{20,}|glpat-[0-9A-Za-z_-]{20,}|sk-(ant|proj)-[A-Za-z0-9_-]{20,}|npm_[A-Za-z0-9]{36}|hooks\.slack\.com/services/T|SG\.[A-Za-z0-9_-]{22}\.[A-Za-z0-9_-]{43}'
PERMITIDO='s#(AKIA|ASIA)[0-9A-Z]{9}EXAMPLE##g; s#://[0-9a-f]{32}(:[0-9a-f]{32})?@(localhost|127\.|[A-Za-z0-9.-]*example|[A-Za-z0-9.-]*\.(invalid|test))##g'
GERADO='code generated|generated code|generated by|automatically generated|@generated|do not edit'
T="$(mktemp -d)" || exit 1
trap 'rm -rf "$T"' EXIT
FALHAS=0
LINGUAGENS=() LISTAS=() IGNORAR=() COMENTARIOS=()
SHA=(openssl dgst -sha256 -r)
command -v shasum > /dev/null 2>&1 && SHA=(shasum -a 256)
command -v sha256sum > /dev/null 2>&1 && SHA=(sha256sum)

falha() { printf 'pre-commit: %s\n' "$*"; FALHAS=$((FALHAS + 1)); }

ler_conf() {
  local n=0 chave resto re='^(go|dart|rs)( [0-9]+( [^ ].*)?)?$'
  [ -f "$CONF" ] || { falha "$CONF não existe"; return; }
  while read -r chave resto || [ -n "$chave" ]; do
    n=$((n + 1))
    case "$chave" in
      '') ;;
      linguagem) [[ $resto =~ $re ]] && LINGUAGENS+=("$resto") || falha "$CONF:$n: use 'linguagem go|dart|rs [limite [prefixo...]]'" ;;
      excecao | teto) LISTAS+=("$chave $resto"); [ -f "${resto#* }" ] || falha "$CONF:$n: a lista ${resto#* } não existe" ;;
      ignorar) IGNORAR+=("$resto") ;;
      comentarios) COMENTARIOS+=("$resto") ;;
      *) falha "$CONF:$n: diretiva desconhecida: $chave" ;;
    esac
  done < "$CONF"
  [ ! -s "$LISTA" ] || ! grep -vqE '^[0-9a-f]{64} sub [1-9][0-9]*$' "$LISTA" || falha "$LISTA: toda linha é '<sha256> sub <tamanho>'"
}

regra() {
  local l ext lim pre p ativa=1
  for l in ${LINGUAGENS[@]+"${LINGUAGENS[@]}"}; do
    read -r ext lim pre <<< "$l"
    [ "$ext" = "$1" ] || continue
    ativa=0
    [ -n "$pre" ] || { echo "${lim:-0}"; return 0; }
    for p in $pre; do case "$2" in "$p"*) echo "${lim:-0}"; return 0 ;; esac; done
  done
  [ "$ativa" = 0 ] && echo 0
  return "$ativa"
}

efetivo() {
  local l tipo ext arq t
  for l in ${LISTAS[@]+"${LISTAS[@]}"}; do
    read -r tipo ext arq <<< "$l"
    [ "$ext" = "$1" ] && [ -f "$arq" ] || continue
    if [ "$tipo" = teto ]; then
      t="$(awk -v a="$2" '$1 == a { print $2; exit }' "$arq")"
      [ -z "$t" ] || { echo "$t"; return; }
    elif sed -E 's/^[[:space:]]+|[[:space:]]+$//g; /^#/d; /^$/d' "$arq" | awk -v a="$2" 'index(a, $0) { f = 1 } END { exit !f }'; then
      echo 0; return
    fi
  done
  echo "$3"
}

edicao() {
  local d="$1" e=
  while [ -z "$e" ] && [ "$d" != . ]; do d="$(dirname "$d")"; e="$(sed -nE 's/^[[:space:]]*edition[[:space:]]*=[[:space:]]*"([0-9]{4})".*/\1/p' "$d/Cargo.toml" 2> /dev/null | head -n 1)"; done
  echo "${e:-2021}"
}

formata() {
  case "$1" in
    go) [ -z "$(gofmt -l 2>&1)" ] ;;
    dart) dart format --output=none --set-exit-if-changed --stdin-name="$2" ;;
    rs) rustfmt --edition "$(edicao "$2")" 2> /dev/null | cmp -s - "$T/blob" ;;
  esac
}

confere_arquivo() {
  local f="$1" e="${1##*.}" lim fmt n p
  case "$e" in go) fmt=gofmt ;; dart) fmt=dart ;; rs) fmt=rustfmt ;; *) return ;; esac
  lim="$(regra "$e" "$f")" || return
  for p in ${IGNORAR[@]+"${IGNORAR[@]}"}; do case "$f" in "$p"*) return ;; esac; done
  git cat-file blob ":$f" > "$T/blob" 2> /dev/null || return
  head -n 5 "$T/blob" | grep -qiE "$GERADO" && return
  if ! command -v "$fmt" > /dev/null 2>&1; then falha "formato: $fmt não está instalado para conferir $f"
  elif ! formata "$e" "$f" < "$T/blob" > /dev/null 2>&1; then falha "formato: $f fora do ${fmt/dart/dart format}"; fi
  n="$(awk 'END { print NR }' "$T/blob")"
  [ "$lim" -gt 0 ] && [ "$n" -gt "$lim" ] && lim="$(efetivo "$e" "$f" "$lim")"
  if [ "$lim" -gt 0 ] && [ "$n" -gt "$lim" ]; then falha "tamanho: $f tem $n linhas (limite $lim)"; fi
}

confere_segredos() {
  local l
  while IFS= read -r l; do falha "possível segredo em $l"; done < <(sed -E "$PERMITIDO" "$T/adicionadas" | grep -E -e "$SEGREDO" | cut -d: -f1,2)
  command -v gitleaks > /dev/null 2>&1 || return 0
  printf '{{range .}}{{.File}}:{{.StartLine}} ({{.RuleID}})\n{{end}}' > "$T/gl.tmpl"
  GITLEAKS_CONFIG_TOML="$(printf '[extend]\nuseDefault = true\ndisabledRules = ["generic-api-key", "jwt"]')" gitleaks protect --staged \
    --no-banner --redact --exit-code 3 --log-level error --report-format template --report-template "$T/gl.tmpl" --report-path "$T/gl.out" > /dev/null 2>&1
  case $? in
    0) ;;
    3) while IFS= read -r l; do falha "gitleaks: possível segredo em $l"; done < "$T/gl.out" ;;
    *) echo "pre-commit: aviso: o gitleaks falhou; os segredos foram conferidos só pela regex" ;;
  esac
}

confere_comentarios() {
  local c a alvo
  set -f
  for c in ${COMENTARIOS[@]+"${COMENTARIOS[@]}"}; do
    set -- $c
    alvo=
    for a in "$@"; do case "$a" in */*) alvo="$a"; break ;; esac; done
    if [ -n "$alvo" ] && [ ! -e "$alvo" ]; then echo "pre-commit: aviso: o portão de comentários $alvo ainda não existe; pulado"; continue; fi
    "$@" > "$T/com" 2>&1 && continue
    sed 's/^/    /' "$T/com"
    falha "comentários: '$c' reprovou"
  done
  set +f
}

confere_palavras() {
  local nome l
  [ -s "$LISTA" ] && [ -s "$T/adicionadas" ] || return 0
  awk -v lista="$LISTA" '
    BEGIN { while ((getline l < lista) > 0) { split(l, c, " "); ns[c[3]] = 1 } }
    {
      i = index($0, ":"); j = index(substr($0, i + 1), ":"); loc = substr($0, 1, i + j - 1); s = substr($0, i + j + 1); u = ""
      for (k = 1; k <= length(s); k++) {
        ch = substr(s, k, 1)
        if (k > 1 && ch ~ /[A-Z]/ && (substr(s, k - 1, 1) !~ /[A-Z]/ || substr(s, k + 1, 1) ~ /[a-z]/)) u = u " "
        u = u ch
      }
      m = split(tolower(u), w, /[^a-z0-9]+/)
      for (k = 1; k <= m; k++) for (n in ns) for (x = 1; x + n - 1 <= length(w[k]); x++) print "s" n "_" substr(w[k], x, n) "\t" loc
    }' "$T/adicionadas" > "$T/cand"
  [ -s "$T/cand" ] || return 0
  mkdir "$T/h"
  while IFS= read -r nome; do printf '%s' "${nome#*_}" > "$T/h/$nome"; done < <(cut -f1 "$T/cand" | sort -u)
  (cd "$T/h" && find . -type f -exec "${SHA[@]}" {} +) | awk 'NR == FNR { quer[$0] = 1; next }
    { n = $2; sub(/^\*?\.\//, "", n); m = n; sub(/_.*/, "", m); if (($1 " sub " substr(m, 2)) in quer) print n "\t" substr($1, 1, 8) }' "$LISTA" - > "$T/achados"
  while IFS= read -r l; do falha "palavra proibida (sha256 ${l%% *}…) em ${l#* }"; done < <(awk -F '\t' 'NR == FNR { a[$1] = $2; next } $1 in a { print a[$1] " " $2 }' "$T/achados" "$T/cand" | sort -u)
}

ler_conf
if [ "${1:-}" = --conferir ]; then [ "$FALHAS" -eq 0 ] && echo "pre-commit: configuração ok"; exit $((FALHAS > 0)); fi
git -c core.quotePath=false diff --cached --raw --no-renames --diff-filter=ACMR | awk -F '\t' '{ split($1, m, " ") } m[2] ~ /^100(644|755)$/ { print $2 }' > "$T/arquivos"
[ -s "$T/arquivos" ] || { echo "pre-commit: nada para conferir"; exit $((FALHAS > 0)); }
git -c core.quotePath=false diff --cached -U0 --no-color --no-ext-diff --no-renames --diff-filter=ACMR --src-prefix=a/ --dst-prefix=b/ \
  | awk '/^diff --git / { h = 1; next } h && /^\+\+\+ / { f = substr($0, 7); next } /^@@ / { h = 0; split($3, p, ","); n = substr(p[1], 2) + 0; next }
    !h && /^\+/ { print f ":" n ":" substr($0, 2); n++ }' > "$T/adicionadas"
while IFS= read -r f; do falha "arquivo sensível: $f"; done < <(awk '{ l = tolower($0) } l ~ /\.(example|sample|template|dist)$/ { next }
  l ~ ENVIRON["SENSIVEL"] || (l !~ ENVIRON["FONTE"] && l ~ ENVIRON["PALAVRA"])' "$T/arquivos")
confere_segredos
while IFS= read -r f; do confere_arquivo "$f"; done < "$T/arquivos"
confere_comentarios
confere_palavras
if [ "$FALHAS" -gt 0 ]; then echo "pre-commit: $FALHAS problema(s); commit recusado"; exit 1; fi
echo "pre-commit: ok"
